/** A lightweight guide that teaches the workflow without mirroring the live UI. */
export function OnboardingGuide({ open, targetLang, onClose }: Props) {
  const [step, setStep] = useState(0);
  const dialogRef = useRef<HTMLDivElement>(null);
  const copy = COPY[targetLang];
  const isLastStep = step === copy.steps.length - 1;

  const closeGuide = useCallback(() => {
    setStep(0);
    onClose();
  }, [onClose]);

  useEffect(() => {
    if (!open) return;

    const previousOverflow = document.body.style.overflow;
    document.body.style.overflow = "hidden";
    requestAnimationFrame(() => dialogRef.current?.focus());

    function handleKeyDown(event: KeyboardEvent) {
      if (event.key === "Escape") closeGuide();
      if (event.key === "ArrowLeft") setStep((current) => Math.max(0, current - 1));
      if (event.key === "ArrowRight") {
        setStep((current) => Math.min(copy.steps.length - 1, current + 1));
      }
    }

    window.addEventListener("keydown", handleKeyDown);
    return () => {
      document.body.style.overflow = previousOverflow;
      window.removeEventListener("keydown", handleKeyDown);
    };
  }, [closeGuide, copy.steps.length, open]);

  if (!open) return null;

  return (
    <div className={styles.overlay} onMouseDown={closeGuide}>
      <div
        ref={dialogRef}
        className={styles.dialog}
        role="dialog"
        aria-modal="true"
        aria-labelledby="onboarding-title"
        tabIndex={-1}
        onMouseDown={(event) => event.stopPropagation()}
      >
        <header className={styles.header}>
          <span className={styles.eyebrow}>{copy.label}</span>
          <button
            type="button"
            className={`${styles.closeButton} btn-interactive`}
            onClick={closeGuide}
            aria-label={copy.close}
            title={copy.close}
          >
            <span aria-hidden="true" style={maskedIconStyle(closeIcon.src, 18)} />
          </button>
        </header>

        <div className={styles.content}>
          <div className={styles.visual} aria-hidden="true">
            {step === 0 && <WelcomeIllustration />}
            {step === 1 && <TextSourceIllustration />}
            {step === 2 && <AnalyzeKnowledgeIllustration />}
            {step === 3 && <ChatIllustration />}
          </div>

          <section className={styles.copy} key={`${targetLang}-${step}`}>
            <span className={styles.stepNumber}>0{step + 1}</span>
            <h2 id="onboarding-title">{copy.steps[step].title}</h2>
            <p className={styles.description}>{copy.steps[step].description}</p>
            <p className={styles.note}>{copy.steps[step].note}</p>
          </section>
        </div>

        <footer className={styles.footer}>
          <button type="button" className={styles.skipButton} onClick={closeGuide}>
            {copy.skip}
          </button>
          <div className={styles.dots} aria-label={`${step + 1} / ${copy.steps.length}`}>
            {copy.steps.map((item, index) => (
              <button
                type="button"
                key={item.title}
                className={`${styles.dot} ${index === step ? styles.dotActive : ""}`}
                onClick={() => setStep(index)}
                aria-label={`${index + 1}`}
                aria-current={index === step ? "step" : undefined}
              />
            ))}
          </div>
          <div className={styles.actions}>
            {step > 0 && (
              <button
                type="button"
                className={`${styles.secondaryButton} btn-interactive`}
                onClick={() => setStep((current) => current - 1)}
              >
                {copy.previous}
              </button>
            )}
            <button
              type="button"
              className={`${styles.primaryButton} btn-interactive`}
              onClick={() => (isLastStep ? closeGuide() : setStep((current) => current + 1))}
            >
              {isLastStep ? copy.start : copy.next}
              {!isLastStep && <span aria-hidden="true">→</span>}
            </button>
          </div>
        </footer>
      </div>
    </div>
  );
}

